// Writes tests/native/*.play: whole tables played through the real UI to their
// results. The opponents' choices depend on the table's clock (js/ai.js seeds
// its stream with the state's hash), so the local seat plays a fixed plan that
// works whatever the dice: each turn waits for its own status line ("Your
// turn · rolls left 3 · round N —"), rolls (R), holds the first die (1),
// rolls again, and scores the next open category of the card in card order,
// clicked on the scorecard by its accessible name ("Score Beams"). The
// scorecard is the Card drawer in the 960 × 540 render check. Re-run after
// content or UI changes:  node tools/gen-plays.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES } from '../js/rules.js';
import { LESSONS, JOURNEY, CHALLENGES } from '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The play-script lines for every one of the local seat's turns of `def`. */
function turns(def) {
  const cats = CATEGORIES.filter((c) => !(def.disabledCategories || []).includes(c.id));
  const rolls = def.rollsPerTurn ?? 3;
  const lines = [];
  cats.forEach((c, i) => {
    lines.push(`until 1200 Your turn · rolls left ${rolls} · round ${i + 1} —`, 'frames 10', 'key KeyR 1', 'frames 8');
    if (rolls > 1) lines.push('key Digit1 1', 'frames 4', 'key KeyR 1', 'frames 8');
    lines.push('frames 5', `click =Score ${c.name}`, 'frames 8');
  });
  return lines;
}
const header = (what) => [`# ${what}`, '# Generated by tools/gen-plays.mjs; regenerate after content or UI changes.'];
const start = ['until 300 Five Dice', 'frames 150'];
const plays = {
  'learn-first-roll': [
    ...header('Learn: lesson 1 (First Roll), a whole table against the Lodge Guide with the Card drawer open, to its results; the Learn list then ticks it.'),
    ...start, 'click =Learn', 'until 60 First Roll', 'frames 10', 'click =1. First Roll',
    'until 120 Press Roll', 'frames 10', 'click =Card', 'frames 10', 'expect Your card — 0/13 filled', 'save lesson',
    ...turns(LESSONS[0]),
    'until 1200 Back to title', 'frames 30', 'expect Lodge Guide', 'save learn-results',
    'click =Back to title', 'until 120 interactive lessons', 'frames 10', 'click =Learn', 'until 60 1. First Roll ✓', 'frames 5',
  ],
  'journey-stage': [
    ...header(`Journey: stage 1 against ${JOURNEY[0].players[1].name} after the 3-2-1 countdown, played to its results, then Play again.`),
    ...start, 'click =Journey', 'until 60 Trail of Sparks', 'frames 10', 'save journey',
    'click =Trail of Sparks 1 — Warming Up', 'until 60 Warming Up', 'frames 150', 'click =Card', 'frames 10',
    ...turns(JOURNEY[0]),
    'until 1200 Back to title', 'frames 30', 'save journey-results', 'expect Par for this table', 'expect Pip',
    'click =Play again', 'until 120 Your turn · rolls left 3 · round 1 —', 'frames 150', 'expect Roll (3)',
  ],
  'challenge-two-roll': [
    ...header('Challenge: Two-Roll Table (two rolls a turn, no undo or hints) against Flint, played to its results.'),
    ...start, 'click =Challenges', 'until 60 Two-Roll Table', 'frames 10', 'click =Two-Roll Table',
    'until 60 Two-Roll Table', 'frames 150', 'click =Card', 'frames 10',
    ...turns(CHALLENGES.find((c) => c.id === 'two-roll-table')),
    'until 1200 Back to title', 'frames 30', 'save challenge-results', 'expect Par for this table: 160', 'expect Flint',
  ],
  'challenge-lone-summit': [
    ...header('Challenge: Lone Summit, a solo card (target 240) played to its results.'),
    ...start, 'click =Challenges', 'until 60 Lone Summit', 'frames 10', 'click =Lone Summit',
    'until 60 Lone Summit', 'frames 150', 'click =Card', 'frames 10',
    ...turns(CHALLENGES.find((c) => c.id === 'lone-summit')),
    'until 1200 Back to title', 'frames 30', 'save solo-results', 'expect Par for this table: 240',
  ],
};
mkdirSync(join(root, 'tests/native'), { recursive: true });
for (const [n, lines] of Object.entries(plays)) {
  writeFileSync(join(root, 'tests/native', `${n}.play`), lines.join('\n') + '\n');
  console.log(`tests/native/${n}.play: ${lines.length} lines`);
}
